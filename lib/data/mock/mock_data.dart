  static List<TimeSlot> generateSlotsForDoctor(
    String doctorId,
    String date,
    List<String> slotTimes,
    Set<String> bookedTimes,
  ) {
    return slotTimes.map((time) {
      return TimeSlot(
        id: '${doctorId}_${date}_${time.replaceAll(':', '')}',
        doctorId: doctorId,
        date: date,
        time: time,
        status: bookedTimes.contains(time) ? SlotStatus.booked : SlotStatus.available,
      );
    }).toList();
  }

